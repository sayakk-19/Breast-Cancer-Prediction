-- Apply once to the app's PostgreSQL database; safe to repeat.
-- Account data is isolated in a dedicated schema.
CREATE SCHEMA IF NOT EXISTS breast_cancer;

CREATE TABLE IF NOT EXISTS breast_cancer.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL CHECK (username ~ '^[A-Za-z0-9_.-]{3,40}$'),
    password_hash TEXT NOT NULL,
    password_salt TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('patient', 'student', 'researcher', 'doctor')),
    approved BOOLEAN NOT NULL DEFAULT FALSE,
    created_at BIGINT NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS users_username_lower
    ON breast_cancer.users (lower(username));

CREATE TABLE IF NOT EXISTS breast_cancer.sessions (
    token_hash TEXT PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES breast_cancer.users(id) ON DELETE CASCADE,
    expires_at BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS sessions_expiry ON breast_cancer.sessions (expires_at);
CREATE INDEX IF NOT EXISTS sessions_user_id ON breast_cancer.sessions (user_id);
